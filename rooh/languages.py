#: الأقاليم بترتيب ثابت
REGIONS: list[str] = []
for _code, _info in LANGUAGES.items():
    if _info[3] not in REGIONS:
        REGIONS.append(_info[3])


def arabic_name(code: str) -> str:
    return LANGUAGES[code][0] if code in LANGUAGES else code


def native_name(code: str) -> str:
    return LANGUAGES[code][1] if code in LANGUAGES else code


def region_of(code: str) -> str:
    return LANGUAGES[code][3] if code in LANGUAGES else "؟"


def codes_in(region: str) -> list[str]:
    return [c for c, i in LANGUAGES.items() if i[3] == region]


def _normalize(weights: dict[str, float]) -> dict[str, float]:
    total = sum(weights.values())
    if total <= 0:
        return weights
    return {k: round(v / total, 5) for k, v in sorted(
        weights.items(), key=lambda kv: kv[1], reverse=True)}


def profile(name: str = "متوازن") -> dict[str, float]:
    """توزيعات جاهزة لأوزان اللغات.

    - متوازن : ٢٠ لغة كبرى — يزور كلاً منها كثيراً بما يكفي ليتعمّق.
    - العالم : كل اللغات المسجّلة — أوسع، لكن كل لغة نصيبها أقل.
    - إقليم  : اسم إقليم من REGIONS، فيتجوّل فيه وحده.
    """
    if name in ("العالم", "world", "all"):
        return _normalize({c: i[4] for c, i in LANGUAGES.items()})
    if name in REGIONS:
        return _normalize({c: LANGUAGES[c][4] for c in codes_in(name)})
    top = sorted(LANGUAGES.items(), key=lambda kv: kv[1][4], reverse=True)[:20]
    return _normalize({c: i[4] for c, i in top})


def describe(codes: Iterable[str]) -> str:
    return "، ".join(f"{arabic_name(c)} ({c})" for c in codes)
